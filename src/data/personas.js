export const getPersonaById = (id) => PERSONAS.find(p => p.id === id) || PERSONAS[0]

export const canAccess = (personaId, pageId) => {
  const persona = getPersonaById(personaId)
  if (!persona) return false
  if (persona.allowedPages.includes('*')) return true
  if (persona.restrictedPages.includes(pageId)) return false
  return persona.allowedPages.some(p => pageId.startsWith(p))
}
